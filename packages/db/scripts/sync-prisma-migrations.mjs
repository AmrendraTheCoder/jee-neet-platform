#!/usr/bin/env node
/**
 * Generate `prisma/migrations/` from `migrations/`.
 *
 * The SQL files are the source of truth. This script projects them into the
 * layout `prisma migrate deploy` expects, so that applying the schema is one
 * command and nobody has to paste seventeen files into the SQL editor in the
 * right order.
 *
 * Two transformations happen on the way, and both matter:
 *
 * 1. The outer `begin;` / `commit;` is stripped. Prisma wraps each migration
 *    file in its own transaction. A nested `begin` is a no-op that warns, but
 *    the inner `commit` ends PRISMA's transaction, so every statement after it
 *    runs unprotected and the engine then fails trying to commit a transaction
 *    that is no longer open. Stripping is what makes the file safe to hand to
 *    Prisma; the atomicity is not lost, it is just owned by the caller now.
 *
 * 2. A provenance header is prepended, because a generated file that looks
 *    hand-written is a file somebody will hand-edit.
 *
 * Directory names keep the numeric prefix rather than taking Prisma's usual
 * timestamp form. Prisma applies migrations in lexicographic order of directory
 * name, and `0001_extensions` < ... < `0015_...` < `0100_...` < `0101_...` is
 * exactly the order the SQL has to run in. A timestamp would encode the same
 * order less legibly and would drift the moment someone regenerated one.
 *
 * Usage:
 *   node scripts/sync-prisma-migrations.mjs           write the migrations
 *   node scripts/sync-prisma-migrations.mjs --check   fail if they have drifted
 */

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const PACKAGE_ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const SOURCE_DIR = join(PACKAGE_ROOT, 'migrations');
const TARGET_DIR = join(PACKAGE_ROOT, 'prisma', 'migrations');

const LOCK = `# Please do not edit this file manually
# It should be added in your version-control system (e.g. Git)
provider = "postgresql"
`;

const checkOnly = process.argv.includes('--check');

/**
 * Remove the outermost transaction control.
 *
 * Deliberately conservative: only a `begin;` that is the first statement and a
 * `commit;` that is the last are removed. A `begin` anywhere else is inside a
 * function body or a DO block, where it is meaningful and must survive.
 */
function stripOuterTransaction(sql) {
  const lines = sql.split('\n');

  const isCode = (line) => {
    const trimmed = line.trim();
    return trimmed !== '' && !trimmed.startsWith('--');
  };

  const firstCode = lines.findIndex(isCode);
  if (firstCode === -1) return { sql, stripped: false };
  if (lines[firstCode].trim().toLowerCase() !== 'begin;') return { sql, stripped: false };

  let lastCode = -1;
  for (let i = lines.length - 1; i >= 0; i -= 1) {
    if (isCode(lines[i])) {
      lastCode = i;
      break;
    }
  }
  if (lastCode === -1 || lines[lastCode].trim().toLowerCase() !== 'commit;') {
    throw new Error('found an opening `begin;` with no matching trailing `commit;`');
  }

  const kept = [...lines.slice(0, firstCode), ...lines.slice(firstCode + 1, lastCode), ...lines.slice(lastCode + 1)];
  return { sql: kept.join('\n').trim(), stripped: true };
}

function render(name, source) {
  const { sql, stripped } = stripOuterTransaction(source);
  const note = stripped
    ? '-- The source file wraps itself in begin/commit. That wrapper is removed here\n' +
      '-- because Prisma runs each migration inside its own transaction, and a nested\n' +
      '-- commit would close it early.\n'
    : '-- The source file manages no transaction of its own; Prisma supplies one.\n';

  return (
    `-- GENERATED FILE. DO NOT EDIT.\n` +
    `--\n` +
    `-- Source: packages/db/migrations/${name}\n` +
    `-- Regenerate with: pnpm db:sync\n` +
    `--\n` +
    note +
    `\n` +
    `${sql}\n`
  );
}

function sourceFiles() {
  if (!existsSync(SOURCE_DIR)) return [];
  return readdirSync(SOURCE_DIR)
    .filter((f) => f.toLowerCase().endsWith('.sql'))
    .sort();
}

function main() {
  const files = sourceFiles();
  if (files.length === 0) {
    console.error(`No SQL migrations found in ${SOURCE_DIR}`);
    process.exit(1);
  }

  const expected = new Map();
  for (const file of files) {
    const name = file.replace(/\.sql$/i, '');
    try {
      expected.set(name, render(file, readFileSync(join(SOURCE_DIR, file), 'utf8')));
    } catch (cause) {
      console.error(`${file}: ${cause instanceof Error ? cause.message : String(cause)}`);
      process.exit(1);
    }
  }

  if (checkOnly) {
    const drift = [];

    if (!existsSync(TARGET_DIR)) {
      drift.push('prisma/migrations does not exist');
    } else {
      const present = readdirSync(TARGET_DIR, { withFileTypes: true })
        .filter((e) => e.isDirectory())
        .map((e) => e.name);

      for (const name of present) {
        if (!expected.has(name)) drift.push(`${name}: generated from a source file that no longer exists`);
      }
      for (const [name, content] of expected) {
        const path = join(TARGET_DIR, name, 'migration.sql');
        if (!existsSync(path)) {
          drift.push(`${name}: missing`);
          continue;
        }
        if (readFileSync(path, 'utf8') !== content) drift.push(`${name}: differs from its source`);
      }
    }

    if (drift.length > 0) {
      console.error('prisma-migration-drift: the applied migrations no longer match the SQL they came from.\n');
      for (const line of drift) console.error(`  ${line}`);
      console.error('\n  fix: run `pnpm db:sync` and commit the result.');
      console.error('       If a migration has ALREADY been deployed, do not regenerate it —');
      console.error('       add a new numbered SQL file instead. Prisma records a checksum per');
      console.error('       migration and refuses to deploy one whose content changed.');
      process.exit(1);
    }

    console.log(`prisma-migration-sync: ${String(expected.size)} migration(s) match their source.`);
    return;
  }

  // Rebuild only the directories this script owns, so a stray hand-made folder
  // is reported rather than silently deleted.
  mkdirSync(TARGET_DIR, { recursive: true });
  if (existsSync(TARGET_DIR)) {
    for (const entry of readdirSync(TARGET_DIR, { withFileTypes: true })) {
      if (entry.isDirectory() && !expected.has(entry.name)) {
        console.warn(`  removing ${entry.name} (no matching source file)`);
        rmSync(join(TARGET_DIR, entry.name), { recursive: true, force: true });
      }
    }
  }

  for (const [name, content] of expected) {
    const dir = join(TARGET_DIR, name);
    mkdirSync(dir, { recursive: true });
    writeFileSync(join(dir, 'migration.sql'), content, 'utf8');
    console.log(`  ${name}/migration.sql`);
  }

  writeFileSync(join(TARGET_DIR, 'migration_lock.toml'), LOCK, 'utf8');
  console.log(`\n${String(expected.size)} migration(s) written to prisma/migrations.`);
}

main();
